<#
.SYNOPSIS
  Desktop UAT of corruption farming on a console game: the Glitch Harvester + RTC over the HTTP API, a stockpile file written by the app and read back by the headless tool.
  Exit 0 = every check passed. Prints one PASS/FAIL line per check.

.DESCRIPTION
  Uses a SNES game GENERATED by the Workshop (--corrupt-test --write-synth-rom): a sprite layer, a sound program in the SPC700 and a one-note instrument in audio RAM. No ROM of anyone's is needed.
  Starts ONE desktop instance (its own PID, its own ports; never touches other instances), then:
    - loads the game, reads GET /api/gh/status (how a position is stored), the memories (GET /api/console/domains, GET /api/rtc/domains)
    - Manual Blast on the audio RAM (POST /api/rtc/blast) and shows by reading the memory back that bytes changed, and only in the audio RAM
    - adds a base, corrupt-and-stash from the current position, keeps it, saves the stockpile file
    - reads the file: format, version, the anchor (a saved machine, with the replay recipe beside it: the SNES has save states), game identity; starts the entry with the Workshop's --corrupt-apply (the same library the FL plugin uses)
    - replays the entry in the app (POST /api/gh/stockpile/{id}/replay): the machine reached has the same audio RAM as the one that was corrupted
    - a reset-like event (swapping the sound unit): a saved machine can still be stored but no replay recipe is offered beside it, and the status says why
    - opens the file back; an older (Lite) export imports
    - the NES path: a NES game loads, blasts as before, the RTC domain sizes show the probed sizes and, with the setting on, the true ones
  It changes the app's config (selected console, corruptionTrueDomainSizes) and puts both back at the end.

.EXAMPLE
  pwsh -File UAT\corruption\desktop-farm.ps1 -Exe <BrokenNes.Windows.exe> -Workshop <BrokenNes.Workshop.exe>
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory)][string]$Exe,
    [Parameter(Mandatory)][string]$Workshop,
    [string]$NesRom,
    [string]$WorkDir = (Join-Path $env:LOCALAPPDATA ('VRUN_Nes_Dev_work\uat_corruption_' + (Get-Date -Format 'yyyyMMdd_HHmmss')))
)
$ErrorActionPreference = 'Stop'
$repo = (Resolve-Path (Join-Path $PSScriptRoot '..\..')).Path
. (Join-Path $repo 'UAT\lib\ApiClient.ps1')
New-Item -ItemType Directory -Force $WorkDir | Out-Null
if (-not $NesRom) { $NesRom = Join-Path $repo 'Windows\Data\story\page1_binty.nes' }

$fails = 0
function Check([string]$name, [bool]$ok, $detail = '') {
    if (-not $ok) { $script:fails++ }
    Write-Host ("[{0}] {1}{2}" -f $(if ($ok) { 'PASS' } else { 'FAIL' }), $name, $(if ("$detail" -ne '') { "  ($detail)" } else { '' }))
}
function Api([string]$method, [string]$path, $body = $null, [hashtable]$query = $null) {
    $a = @{ ProcessId = $script:pid_; Method = $method; Path = $path; Raw = $true }
    if ($null -ne $body) { $a.Body = $body }
    if ($null -ne $query) { $a.Query = $query }
    Invoke-BrokenNesApi @a
}
function Aram() {
    $all = New-Object 'System.Collections.Generic.List[int]'
    for ($a = 0; $a -lt 65536; $a += 4096) {
        $r = Api GET '/api/console/peek' $null @{ domain = 'ARAM'; address = $a; length = 4096 }
        foreach ($b in $r.Body.data) { $all.Add([int]$b) }
    }
    return ,$all.ToArray()
}
function ByteDiff($x, $y) { $d = @(); for ($i = 0; $i -lt $x.Length; $i++) { if ($x[$i] -ne $y[$i]) { $d += $i } }; return ,$d }

$inst = $null; $script:pid_ = 0; $startConsole = $null; $trueSizesStart = $false; $volStart = $null; $snesCoresStart = $null
try {
    # ---- the game
    $romFile = Join-Path $WorkDir 'synth.sfc'
    & $Workshop --corrupt-test --write-synth-rom $romFile | Out-String | Out-Null
    Check 'the Workshop wrote the generated SNES game' (Test-Path $romFile) "$((Get-Item $romFile).Length) bytes"
    $sha1 = (Get-FileHash $romFile -Algorithm SHA1).Hash.ToLowerInvariant()

    # ---- the app
    $inst = Start-BrokenNesInstance -ExePath $Exe -TimeoutSeconds 120
    $script:pid_ = $inst.ProcessId
    Check 'the app started and its API answers (our PID only)' ($script:pid_ -gt 0) "pid $($script:pid_)"
    Start-Sleep -Seconds 5      # the app finishes loading its embedded ROM a few seconds after the API answers
    $startConsole = (Api GET '/api/console').Body.status.console
    # the generated game sounds a 2 kHz tone: mute the app for the run (the setting is the app's, so it is put back at the end)
    $volStart = (Api GET '/api/audio/emulation-volume').Body.state
    Api POST '/api/audio/emulation-volume' @{ muted = $true } | Out-Null
    $trueSizesStart = [bool](Api GET '/api/rtc/true-domain-sizes').Body.enabled

    # a position can be stored as a replay from power-on only on the console's own sound unit: the player's config may name another (a bridge), so the SNES is put on its own for the run and put back after
    Api POST '/api/console/select/snes' | Out-Null
    Start-Sleep -Seconds 1
    $snesCoresStart = (Api GET '/api/console').Body.status
    Api POST '/api/console/core/cpu/SFC' | Out-Null
    Api POST '/api/console/core/apu/SFC' | Out-Null
    $r = Api POST '/api/emulator/load-rom' @{ Path = $romFile }
    Check 'load the SNES game' ($r.Body.success -eq $true) ($r.Content)
    Start-Sleep -Seconds 4
    $c = (Api GET '/api/console').Body
    Check 'the app runs it as a SNES game' ($c.status.console -eq 'snes' -and $c.status.game -like 'BN CORRUPTION*') "$($c.status.description)"

    # ---- what the farm can do
    $st = (Api GET '/api/gh/status').Body
    Check 'status: a console game is being farmed; the SNES has save states, so a position is stored as a saved machine with the replay recipe beside it' ($st.farm.active -eq $true -and $st.farm.positions -eq 'state' -and $st.farm.replayRecipe -eq $true) "positions=$($st.farm.positions) replayRecipe=$($st.farm.replayRecipe) frames=$($st.farm.frames)"
    $dom = (Api GET '/api/console/domains').Body.domains
    $ids = ($dom | ForEach-Object { $_.id }) -join ','
    Check 'the game has its eight memories at their true sizes (ARAM 65,536, WRAM 131,072)' ($ids -eq 'WRAM,VRAM,CGRAM,OAM,SRAM,ROM,ARAM,DSP' -and ($dom | Where-Object id -eq 'ARAM').size -eq 65536 -and ($dom | Where-Object id -eq 'WRAM').size -eq 131072) $ids
    $rtc = (Api GET '/api/rtc/domains').Body.domains
    Check 'the RTC tab lists the same memories' (($rtc | Measure-Object).Count -eq 8 -and ($rtc | Where-Object key -eq 'ARAM').size -eq 65536) "WRAM selected by default: $(($rtc | Where-Object key -eq 'WRAM').selected)"

    # ---- Manual Blast on the audio RAM
    Api POST '/api/rtc/domains/selection' @{ SelectedDomains = @('ARAM') } | Out-Null
    Api POST '/api/rtc/intensity' @{ Intensity = 8 } | Out-Null
    Api POST '/api/rtc/blast-type' @{ BlastType = 'BITFLIP' } | Out-Null
    $before = Aram
    $b = Api POST '/api/rtc/blast'
    Check 'Manual Blast on a console game applies its 8 writes' ($b.Body.success -eq $true -and $b.Body.writesApplied -eq 8) $b.Body.message
    $after = Aram
    $changed = ByteDiff $before $after
    Check 'the audio RAM changed (and in at most 8 bytes: the game itself does not write there)' ($changed.Count -ge 1 -and $changed.Count -le 8) "$($changed.Count) bytes at $((($changed | Select-Object -First 4) | ForEach-Object { '$' + ('{0:X4}' -f [int]$_) }) -join ' ')"

    # ---- base, corrupt-and-stash, keep, save the file
    $base = Api POST '/api/gh/base-state' @{ Name = 'synth' }
    Check 'a base is taken as a saved machine' ($base.Body.success -eq $true -and $base.Body.baseState.anchor -eq 'state') "$($base.Body.baseState.anchor)"
    Api POST '/api/gh/load-on-operation' @{ Enabled = $false } | Out-Null
    Api POST '/api/rtc/domains/selection' @{ SelectedDomains = @('ARAM') } | Out-Null
    $stash = Api POST '/api/gh/corrupt-and-stash' @{}
    Check 'corrupt-and-stash blasts the running game from where it is and stores the position' ($stash.Body.success -eq $true -and $stash.Body.entry.writeCount -eq 8 -and $stash.Body.entry.anchor -eq 'state') "$($stash.Body.entry.summary)"
    $entryId = $stash.Body.entry.id
    $afterStash = Aram                                 # the machine that was corrupted
    $kept = Api POST "/api/gh/stash/$entryId/promote"
    Check 'keep: the entry moves to the stockpile' ($kept.Body.success -eq $true)
    Api PUT "/api/gh/stockpile/$entryId/rename" @{ Name = 'Synth growl'; Description = 'eight bits flipped in the instrument' } | Out-Null
    $list = (Api GET '/api/gh/stockpile').Body.stockpile
    Check 'the stockpile lists it with its name, description, game and how it starts' ($list.Count -eq 1 -and $list[0].name -eq 'Synth growl' -and $list[0].description -like 'eight bits*' -and $list[0].console -eq 'snes') "$($list[0].summary) / $($list[0].anchor)"
    $file = Join-Path $WorkDir 'farm.stockpile.json'
    $save = Api POST '/api/gh/stockpile/save' @{ Path = $file }
    Check 'save the stockpile to a file' ($save.Body.success -eq $true -and (Test-Path $file)) $save.Body.message

    # ---- the file itself
    $j = Get-Content $file -Raw | ConvertFrom-Json
    Check 'the file is a v2 stockpile with one entry whose game is this ROM (sha1) and whose anchor is a saved machine with the replay recipe beside it' ($j.format -eq 'brokennes-stockpile' -and $j.version -eq 2 -and $j.entries.Count -eq 1 -and $j.entries[0].game.sha1 -eq $sha1 -and $j.entries[0].game.console -eq 'snes' -and $j.entries[0].anchor.kind -eq 'state' -and $j.entries[0].anchor.alt.kind -eq 'boot' -and $j.entries[0].anchor.alt.frames -gt 0) "anchor $($j.entries[0].anchor.kind) + alt $($j.entries[0].anchor.alt.kind) $($j.entries[0].anchor.alt.frames) frames, $((Get-Item $file).Length) bytes"
    Check 'no path of this machine is in the file' (-not ((Get-Content $file -Raw) -match [regex]::Escape($env:USERNAME)))

    # ---- the same file started by the headless tool (the library the FL plugin uses)
    $o = & $Workshop --corrupt-apply --rom $romFile --stockpile $file --frames 60 | Out-String
    Check 'the headless tool starts the entry from the file: 8 writes applied, only the audio RAM differs from the clean run' ($LASTEXITCODE -eq 0 -and $o -match 'started .*8 of 8 writes applied' -and $o -match 'ARAM\s+[1-8] of') ($o -split "`n" | Where-Object { $_ -match 'ARAM' } | Select-Object -First 1)

    # ---- the app replays it
    $rep = Api POST "/api/gh/stockpile/$entryId/replay"
    Check 'start in the app: the saved machine is loaded and the writes land' ($rep.Body.success -eq $true -and $rep.Body.message -match 'loaded its saved machine' -and $rep.Body.message -match '8 of 8 writes applied') "$($rep.Body.message)"
    Start-Sleep -Milliseconds 700
    $afterReplay = Aram
    $dd = ByteDiff $afterStash $afterReplay
    Check 'the started machine has the very audio RAM of the machine that was corrupted' ($dd.Count -eq 0) "$($dd.Count) bytes differ"
    $st2 = (Api GET '/api/gh/status').Body.farm
    Check 'the game''s save RAM is protected after a start (nothing from the started machine is written over a player''s save)' ($st2.saveRamProtected -eq $true)

    # ---- open the file again
    Api DELETE "/api/gh/stockpile/$entryId" | Out-Null
    $open = Api POST '/api/gh/stockpile/open' @{ Path = $file }
    Check 'open the file again: the entry is back with its name and description' ($open.Body.success -eq $true -and $open.Body.imported -eq 1 -and ((Api GET '/api/gh/stockpile').Body.stockpile[0].name -eq 'Synth growl'))
    $bad = Join-Path $WorkDir 'bad.json'; Set-Content $bad '{ not json'
    $ob = Api POST '/api/gh/stockpile/open' @{ Path = $bad }
    Check 'a file that is not a stockpile is refused with the reason, the stockpile is untouched' ($ob.StatusCode -ge 400 -and $ob.Content -match 'not valid JSON' -and ((Api GET '/api/gh/stockpile').Body.stockpile.Count -eq 1))
    $lite = '[{"Id":"22222222-2222-2222-2222-222222222222","Name":"From Lite","BaseStateId":"b","Created":"2026-09-02T10:00:00Z","Writes":[{"Domain":"CHR","Address":7,"Value":9}],"BaseState":"{\"romHash\":\"ab\"}"}]'
    $imp = Api POST '/api/gh/stockpile/import' @{ Json = $lite }
    Check 'an older export (Lite''s, with BaseState) imports and says how many' ($imp.Body.success -eq $true -and $imp.Body.imported -eq 1) $imp.Body.message
    $rn = Api POST '/api/gh/stockpile/22222222-2222-2222-2222-222222222222/replay'
    Check 'a NES entry is refused on a console game, with the reason' ($rn.StatusCode -ge 400 -and $rn.Content -match 'NES')

    # ---- an event that a replay cannot reproduce: the sound unit swapped (the saved machine is still a position; the replay recipe is not offered, and the status says why)
    Api POST '/api/console/core/apu/HLE' | Out-Null
    Start-Sleep -Milliseconds 500
    $stSwap = (Api GET '/api/gh/status').Body.farm
    Check 'after the sound unit was swapped the status says no replay recipe can be stored, and why' ($stSwap.replayRecipe -eq $false -and $stSwap.replayReason -match 'swapped') "replayRecipe=$($stSwap.replayRecipe): $($stSwap.replayReason)"
    $bs = Api POST '/api/gh/base-state' @{ Name = 'after the swap' }
    Check 'a base is still stored as a saved machine (it belongs to the sound unit it was taken under), with no replay recipe beside it' ($bs.StatusCode -lt 300 -and $bs.Body.baseState.anchor -eq 'state') "$($bs.Content)"
    Api POST '/api/console/core/apu/SFC' | Out-Null

    # ---- the NES path
    if (Test-Path $NesRom) {
        $ln = Api POST '/api/emulator/load-rom' @{ Path = (Resolve-Path $NesRom).Path }
        Start-Sleep -Seconds 4
        $stn = (Api GET '/api/gh/status').Body
        Check 'NES game: no console farm (the NES keeps its own saved states)' ($stn.farm.active -eq $false)
        Api POST '/api/rtc/domains/selection' @{ SelectedDomains = @('RAM') } | Out-Null
        $nb = Api POST '/api/rtc/blast'
        Check 'NES game: Manual Blast works as before' ($nb.Body.success -eq $true) $nb.Body.message
        Api POST '/api/rtc/true-domain-sizes' @{ Enabled = $false } | Out-Null
        Start-Sleep -Milliseconds 700
        $probed = (Api GET '/api/rtc/domains').Body.domains
        Api POST '/api/rtc/true-domain-sizes' @{ Enabled = $true } | Out-Null
        Start-Sleep -Milliseconds 700
        $true_ = (Api GET '/api/rtc/domains').Body.domains
        $fmt = { param($d) ($d | ForEach-Object { "$($_.key)=$($_.size)" }) -join ' ' }
        Check 'NES game: the RTC domain sizes are the probed ones by default and the real ones with the setting on' ((($true_ | Where-Object key -eq 'PRG').size -gt (($probed | Where-Object key -eq 'PRG').size)) -and (($true_ | Where-Object key -eq 'RAM').size -eq 2048)) ("probed: " + (& $fmt $probed) + " | true: " + (& $fmt $true_))
        Api POST '/api/gh/base-state' @{ Name = 'nes base' } | Out-Null
        $ns = Api POST '/api/gh/corrupt-and-stash' @{}
        Check 'NES game: corrupt-and-stash still works and keeps the NES saved state' ($ns.Body.success -eq $true -and $ns.Body.entry.anchor -eq 'state') $ns.Body.entry.summary
    } else { Write-Host "[SKIP] the NES checks: no NES ROM at $NesRom" }
}
finally {
    try { if ($script:pid_ -gt 0) { Api POST '/api/rtc/true-domain-sizes' @{ Enabled = $trueSizesStart } | Out-Null } } catch { }
    try { if ($script:pid_ -gt 0 -and $volStart) { Api POST '/api/audio/emulation-volume' @{ muted = [bool]$volStart.muted } | Out-Null } } catch { }
    try { if ($script:pid_ -gt 0 -and $snesCoresStart) { Api POST '/api/console/select/snes' | Out-Null; Start-Sleep -Milliseconds 800; Api POST "/api/console/core/cpu/$($snesCoresStart.cpu)" | Out-Null; Api POST "/api/console/core/apu/$($snesCoresStart.apu)" | Out-Null } } catch { }
    try { if ($script:pid_ -gt 0 -and $startConsole) { Api POST "/api/console/select/$startConsole" | Out-Null } } catch { }
    if ($script:pid_ -gt 0) { Stop-BrokenNesInstance -ProcessId $script:pid_ | Out-Null }
}
Write-Host ""
Write-Host $(if ($fails -eq 0) { 'ALL CHECKS PASSED' } else { "$fails CHECK(S) FAILED" })
exit $(if ($fails -eq 0) { 0 } else { 1 })
