class TilePool:
    """8-bit tiles, deduplicated (with flips), for one 64 KB tile unit; tile 0 is empty."""
    def __init__(self):
        self.tiles = [bytes(64)]; self.index = {bytes(64): (0, 0)}
    def add(self, px):
        t = tile_bytes(px, 8)
        if t in self.index: return self.index[t]
        for flip, f in ((0x4000, lambda p: [r[::-1] for r in p]), (0x8000, lambda p: p[::-1]), (0xC000, lambda p: [r[::-1] for r in p[::-1]])):
            k = tile_bytes(f(px), 8)
            if k in self.index: return (self.index[k][0], flip)
        n = len(self.tiles); self.tiles.append(t); self.index[t] = (n, 0)
        assert n < 1024
        return (n, 0)
    def entry(self, px, prio=False):
        n, flip = self.add(px)
        return n | flip | (0x1000 if prio else 0)
    def blob(self): return b''.join(self.tiles)

def image_to_map(img, pool, w_tiles=64, h_tiles=32, prio=False):
    """img[y][x] colour indices (0 = transparent), at most w_tiles*8 x h_tiles*8: a 64 x 32 map (row by row)."""
    m = [0] * (w_tiles * h_tiles)
    H, W = len(img), len(img[0])
    for ty in range(h_tiles):
        for tx in range(w_tiles):
            px = [[img[ty * 8 + y][tx * 8 + x] if ty * 8 + y < H and tx * 8 + x < W else 0 for x in range(8)] for y in range(8)]
            m[ty * w_tiles + tx] = pool.entry(px, prio) if any(any(r) for r in px) else 0
    return words(m)

