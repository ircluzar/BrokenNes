// Builds Nano/gb/dist from Nano/gb/src:  node Nano/gb/build.mjs            (writes dist/ and the plugin's preset table)
//                                        node Nano/gb/build.mjs --check    (rebuilds in memory and compares; exit 1 if anything differs)
//
// No dependencies, no minifier.
//   dist/nano-gb.js          the whole library as a classic script (global BrokenNesNanoGB, or CommonJS require), comments included
//   dist/nano-gb.mjs         the same as an ES module
//   dist/nano-gb-worklet.js  only the audio worklet, for pages whose Content-Security-Policy forbids blob: scripts
//   dist/nano-gb.lean.js     nano-gb.js without comments or indentation (the same code: test/engine.test.mjs renders both and compares)
//   dist/NOTICE.txt          the credits and licences that travel with the files
//   ../../Windows/NesEmulator/gb/NanoGbPresets.g.cs   the normalized presets as JSON, for the C# twin (the BrokenNes2 plugin's Nano GB chip)
