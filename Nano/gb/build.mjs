// Comments and indentation out; strings, template literals and regular expressions are kept as they are (a small tokenizer, not a minifier).
function lean(src) {
  let out = '', i = 0, prev = '';
  const n = src.length;
  const regexOk = () => { const t = out.replace(/\s+$/, ''); const c = t[t.length - 1]; return !c || '(,=:[!&|?{};+-*%<>~^'.includes(c) || /\b(return|typeof|case|of|in)$/.test(t); };
  while (i < n) {
    const c = src[i], d = src[i + 1];
    if (c === '/' && d === '/') { while (i < n && src[i] !== '\n') i++; continue; }
    if (c === '/' && d === '*') { const keep = src[i + 2] === '!'; const j = src.indexOf('*/', i + 2) + 2; if (keep) out += src.slice(i, j); i = j; continue; }
    if (c === '"' || c === "'" || c === '`') {
      let j = i + 1;
      while (j < n && src[j] !== c) { if (src[j] === '\\') j++; else if (c === '`' && src[j] === '$' && src[j + 1] === '{') { let depth = 1; j += 2; while (j < n && depth) { if (src[j] === '{') depth++; else if (src[j] === '}') depth--; else if (src[j] === "'" || src[j] === '"') { const q = src[j]; j++; while (src[j] !== q) { if (src[j] === '\\') j++; j++; } } if (depth) j++; } } j++; }
      out += src.slice(i, j + 1); i = j + 1; continue;
    }
    if (c === '/' && regexOk()) {
      let j = i + 1, cls = false;
      while (j < n && (src[j] !== '/' || cls)) { if (src[j] === '\\') j++; else if (src[j] === '[') cls = true; else if (src[j] === ']') cls = false; j++; }
      j++; while (/[a-z]/.test(src[j])) j++;
      out += src.slice(i, j); i = j; continue;
    }
    out += c; i++;
  }
  return out.split('\n').map(l => l.trim()).filter(l => l.length).join('\n') + '\n';
}
files['nano-gb.lean.js'] = lean(files['nano-gb.js']);
files['NOTICE.txt'] = notice;

// the C# twin's preset table
const kit = new Function(`${kitFn}\nreturn engineKit();`)();
const table = { presets: kit.PRESET_NAMES.map(k => kit.normalizePreset(kit.PRESETS[k], k)), drums: kit.GM_DRUMS };
const json = JSON.stringify(table);
const cs = `// <auto-generated> by Nano/gb/build.mjs from Nano/gb/src/presets.js: do not edit (node Nano/gb/build.mjs rewrites it, --check compares). </auto-generated>
namespace NesEmulator.Gb;

public static partial class NanoGbPresets
{
    /// <summary>The web library's normalized presets in program order, and the General MIDI drum map.</summary>
    public const string Json = ${JSON.stringify(json)};
}
`;

const check = process.argv.includes('--check');
let bad = 0;
function emit(target, data, label) {
  const buf = Buffer.from(data, 'utf8');
  if (check) {
    const have = fs.existsSync(target) ? Buffer.from(fs.readFileSync(target, 'utf8').split('\r\n').join('\n'), 'utf8') : null;   // (a checkout with core.autocrlf has CRLF line ends)
    if (!have || !have.equals(buf)) { console.error(`DIFFERS: ${label}`); bad++; } else console.log(`same: ${label} (${buf.length} bytes)`);
  } else { fs.mkdirSync(path.dirname(target), { recursive: true }); fs.writeFileSync(target, buf); console.log(`wrote ${label} (${buf.length} bytes)`); }
}
for (const [name, d] of Object.entries(files)) emit(path.join(root, 'dist', name), d, 'dist/' + name);
emit(path.join(root, '..', '..', 'Windows', 'NesEmulator', 'gb', 'NanoGbPresets.g.cs'), cs, 'Windows/NesEmulator/gb/NanoGbPresets.g.cs');
process.exit(bad ? 1 : 0);
