// The music pipeline's Vaults DOS / Vaults 95 back end: both PC ports keep the Game Gear port's PSG music driver UNCHANGED (VRUN_VOC_DOS_dev src/voc_sound.c, the same file in
// VRUN_VOC_95_dev) and play its PSG bytes on an OPL2 (src/dos/dos_opl.c on DOS, src/win/win_opl.c + Nuked OPL3 on Windows: the same mapping). So the song is VocGgBackend's (the Game
// Boy song bytes, unchanged) and this file only re-reads the Game Gear fence for the PC: the PSG rules all hold (the driver is the same), the frame rate does not (the PCs run the
// Game Boy's 59.727 Hz: PIT divisor 19977), and the OPL2's own differences are added (dos_opl.c, read):
//   tones 0-2 -> melodic voices 0-2, a two-operator FM patch (modulator x2: odd harmonics, square-LIKE, not a square); the PSG's 2 dB attenuation -> the carrier's 0.75 dB levels;
//   noise -> the rhythm mode's snare drum (the OPL2's noise generator), its pitch from the PSG noise rate; a hit retriggers it (the PSG's write resets its shift register);
//   no Sound Blaster DSP, no stereo (mono on DOS and on Windows).
// Nothing is dropped silently: every Game Gear line is kept (the timing line replaced), each OPL difference is a note line.
namespace BrokenNes2.Music.Flp;

public static class VocDosBackend
{
    public const double Fps = 1193182.0 / 19977.0;   // 59.727 Hz (src/dos/dos_plat.c PIT_DIV; Vaults 95's clock is the same)

    public static VocSong Build(FlpSongModel song, string name)
    {
        var v = VocGgBackend.Build(song, name);
        var F = v.Fence;
        for (int i = 0; i < F.Count; i++)
        {
            var l = F[i];
            if (l.Rule == "timing")
            {
                double d = (Fps / VocGbBackend.Fps - 1) * 100;
                F[i] = new FenceLine("timing", Math.Abs(d) < 0.01 ? FenceLevel.Ok : FenceLevel.Note, $"the PC ports' frame is {Fps:0.000} Hz (the Game Boy's): the song plays at its own speed ({d:+0.000;-0.000}%)");
            }
            else F[i] = l with { Text = l.Text.Replace("Game Gear driver", "Game Gear driver (kept unchanged on DOS / 95)").Replace("the Game Gear PSG's", "the PSG's (the Game Gear driver's limit, kept on DOS / 95)") };
        }
        for (int i = F.Count - 1; i > 0; i--) if (F.FindIndex(x => x == F[i]) < i) F.RemoveAt(i);   // (the Game Boy and Game Gear timing lines both became the PC's: one is kept)
        int tones = v.Notes[0] + v.Notes[1] + v.Notes[2];
        if (tones > 0) F.Add(new FenceLine("opl tone", FenceLevel.Note, $"{tones} tone notes play on OPL2 FM voices 0-2 (carrier x1 + modulator x2: square-like, not a PSG square); levels on the carrier's 0.75 dB steps"));
        if (v.Notes[3] > 0) F.Add(new FenceLine("opl noise", FenceLevel.Note, $"{v.Notes[3]} noise hits play on the OPL2 rhythm mode's snare (its noise generator), pitch from the PSG rate, retriggered by each hit"));
        F.Add(new FenceLine("opl", FenceLevel.Ok, "4 channels -> OPL2 voices 0-2 + the snare: every channel has a voice (no steals); mono"));
        return v;
    }

    /// <summary>The song as C for the music test's FL slot (musictest/mt_fl.c in VRUN_VOC_DOS_dev / VRUN_VOC_95_dev): the four streams, the noise rates, the title.</summary>
    public static string CSource(VocSong s, string title)
    {
        var sb = new System.Text.StringBuilder();
        sb.Append("/* GENERATED by FruityHost flp-vocdos (Music/Flp/VocDosBackend.cs) from ").Append(Clean(title)).Append(": do not edit. */\n#include <stdint.h>\n");
        sb.Append("const char mt_fl_title[] = \"").Append(Clean(title)).Append("\";\nconst uint8_t mt_fl_present = 1;\n");
        for (int c = 0; c < 4; c++)
        {
            sb.Append($"const uint8_t mt_fl_ch{c}[{Math.Max(1, s.Streams[c].Length)}] = {{");
            for (int i = 0; i < s.Streams[c].Length; i++) sb.Append(i % 24 == 0 ? "\n    " : " ").Append($"0x{s.Streams[c][i]:X2},");
            sb.Append("\n};\n");
        }
        var nr = new int[128];
        for (int i = 0; i < s.Noise.Count && i < 128; i++) nr[i] = VocGgBackend.NoiseRate(s.Noise[i]);
        sb.Append("const uint8_t mt_fl_nrate[128] = { ").Append(string.Join(", ", nr)).Append(" };\n");
        return sb.ToString();
    }

    private static string Clean(string t) => new([.. t.Select(ch => ch is >= ' ' and <= '~' and not '"' and not '\\' and not '*' ? ch : '_')]);
}
