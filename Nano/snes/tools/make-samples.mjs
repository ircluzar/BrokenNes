// Makes the built-in samples of Nano SNES (src/samples.js): single-cycle waveforms and a few one-shot drums, as 16-bit PCM encoded to BRR by the
// engine's own encoder (filter 0). Run once when a sample changes:  node Nano/snes/tools/make-samples.mjs
// The output is literal base64, so the library never computes a sine at run time (the bytes are the same in every browser and in the C# twin).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const engineSrc = fs.readFileSync(path.join(here, '..', 'src', 'engine.js'), 'utf8');
const { encodeBrr, toBase64 } = new Function(engineSrc.slice(engineSrc.indexOf('const B64'), engineSrc.indexOf('function normalizePreset')) + 'return { encodeBrr, toBase64 };')();

const A = 24000;
const cyc = (n, f) => Array.from({ length: n }, (_, i) => Math.round(A * f(i / n)));
const sine = (x) => Math.sin(2 * Math.PI * x);
const add = (parts) => (x) => parts.reduce((s, [h, a]) => s + a * Math.sin(2 * Math.PI * h * x), 0);
const norm = (f, n) => { const raw = Array.from({ length: n }, (_, i) => f(i / n)); const pk = Math.max(...raw.map(Math.abs)); return (x) => f(x) / pk; };
// band-limited (additive) versions of the classic shapes for a 32-sample cycle: harmonics up to 15
const H = 15;
const saw = norm(add(Array.from({ length: H }, (_, k) => [k + 1, 1 / (k + 1)])), 64);
const square = norm(add(Array.from({ length: H }, (_, k) => [k + 1, (k + 1) % 2 ? 1 / (k + 1) : 0])), 64);
const pulse = (duty) => norm(add(Array.from({ length: H }, (_, k) => [k + 1, Math.sin(Math.PI * (k + 1) * duty) / (k + 1)])), 64);
const tri = norm(add(Array.from({ length: H }, (_, k) => [k + 1, (k + 1) % 2 ? ((k >> 1) % 2 ? -1 : 1) / ((k + 1) * (k + 1)) : 0])), 64);
const organ = norm(add([[1, 1], [2, 0.6], [3, 0.35], [4, 0.3], [6, 0.18], [8, 0.12]]), 64);
const strings = norm(add(Array.from({ length: H }, (_, k) => [k + 1, 1 / Math.pow(k + 1, 1.3)])), 64);
const brass = norm(add([[1, 1], [2, 0.8], [3, 0.65], [4, 0.5], [5, 0.38], [6, 0.28], [7, 0.2], [8, 0.14]]), 64);
const choir = norm(add([[1, 1], [2, 0.35], [3, 0.12], [5, 0.08]]), 64);
const bell = norm(add([[1, 1], [2.0, 0.5], [3, 0.25], [4, 0.4], [7, 0.15]]), 64);

// one-shots at 32 kHz: a falling sine (kick), a tom
function sweep(n, f0, f1, decay) { let ph = 0; return Array.from({ length: n }, (_, i) => { const t = i / n, f = f0 * Math.pow(f1 / f0, t); ph += f / 32000; return Math.round(A * Math.sin(2 * Math.PI * ph) * Math.exp(-decay * t)); }); }

const loops = {
  sine: cyc(32, sine), square: cyc(32, square), pulse25: cyc(32, pulse(0.25)), pulse12: cyc(32, pulse(0.125)), saw: cyc(32, saw), triangle: cyc(32, tri),
  organ: cyc(32, organ), strings: cyc(32, strings), brass: cyc(32, brass), choir: cyc(32, choir), bell: cyc(32, bell),
  bass: cyc(64, norm(add([[1, 1], [2, 0.5], [3, 0.3], [4, 0.15]]), 64)),
};
const shots = { kick: sweep(3200, 160, 45, 3), tom: sweep(4800, 220, 110, 3) };

let out = `// ---- samples: the built-in BRR samples of Nano SNES (generated by tools/make-samples.mjs: do not edit by hand) ------------------------------
//
// Single-cycle loops (32 samples = 1000 Hz at pitch $1000, 64 = 500 Hz) and two one-shot drums (32 kHz, base = their pitch at $1000), 16-bit PCM encoded
// to BRR (filter 0). Band-limited shapes: harmonics up to the 15th.
const SAMPLES = {\n`;
for (const [k, pcm] of Object.entries(loops)) out += `  ${k}: { brr: '${toBase64(encodeBrr(pcm, 0))}', loop: 0, base: ${32000 / pcm.length} },\n`;
for (const [k, pcm] of Object.entries(shots)) out += `  ${k}: { brr: '${toBase64(encodeBrr(pcm, -1))}', loop: -1, base: 261.6255653005986 },\n`;
out += '};\n';
fs.writeFileSync(path.join(here, '..', 'src', 'samples.js'), out);
console.log('wrote src/samples.js');
