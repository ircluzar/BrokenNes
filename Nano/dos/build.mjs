// Comments and indentation out; strings, template literals and regular expressions are kept as they are (a small tokenizer, not a minifier).
function lean(src) {
  let out = '', i = 0, prev = '';
  const n = src.length;
  const regexOk = () => { const t = out.replace(/\s+$/, ''); const c = t[t.length - 1]; return !c || '(,=:[!&|?{};+-*%<>~^'.includes(c) || /\b(return|typeof|case|of|in)$/.test(t); };
  while (i < n) {
    const c = src[i], d = src[i + 1];
    if (c === '/' && d === '/') { while (i < n && src[i] !== '\n') i++; continue; }
    if (c === '/' && d === '*') { const keep = src[i + 2] === '!'; const j = src.indexOf('*/', i + 2) + 2; if (keep) out += src.slice(i, j); i = j; continue; }
    if (c === '"' || c === "'" || c === '`') {
      let j = i + 1;
      while (j < n && src[j] !== c) { if (src[j] === '\\') j++; else if (c === '`' && src[j] === '$' && src[j + 1] === '{') { let depth = 1; j += 2; while (j < n && depth) { if (src[j] === '{') depth++; else if (src[j] === '}') depth--; else if (src[j] === "'" || src[j] === '"') { const q = src[j]; j++; while (src[j] !== q) { if (src[j] === '\\') j++; j++; } } if (depth) j++; } } j++; }
      out += src.slice(i, j + 1); i = j + 1; continue;
    }
    if (c === '/' && regexOk()) {
      let j = i + 1, cls = false;
      while (j < n && (src[j] !== '/' || cls)) { if (src[j] === '\\') j++; else if (src[j] === '[') cls = true; else if (src[j] === ']') cls = false; j++; }
      j++; while (/[a-z]/.test(src[j])) j++;
      out += src.slice(i, j); i = j; continue;
    }
    out += c; i++;
  }
  return out.split('\n').map(l => l.trim()).filter(l => l.length).join('\n') + '\n';
}
files['nano-dos.lean.js'] = lean(files['nano-dos.js']);
files['NOTICE.txt'] = notice;

