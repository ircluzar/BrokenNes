# the logo: WIDEMESS from the font scaled 4 times, a gradient by row, a dark edge and a drop shadow; TEST CARTRIDGE scaled 2 times below
def text_bitmap(text, scale):
    cols = []
    for ch in text:
        rows = GLYPHS.get(ch, [])
        w = max([len(r) for r in rows] + [6]) if ch != ' ' else 4
        for x in range(w):
            col = [(x < len(rows[y]) and rows[y][x] == '#') if y < len(rows) else False for y in range(7)]
            cols += [col] * scale
        cols += [[False] * 7] * scale        # a gap of one font pixel
    return [[cols[x][y // scale] for x in range(len(cols))] for y in range(7 * scale)]
