BLOCK = 1                                   # code 1: a solid 8 x 8 block (colour 1, no shadow); codes 9-15: 1-7 pixels of it from the left
def glyph_pixels(code):
    px = [[0] * 8 for _ in range(8)]
    if code == BLOCK or 9 <= code <= 15:
        w = 8 if code == BLOCK else code - 8
        for y in range(8):
            for x in range(w): px[y][x] = 1
        return px
    rows = SPECIAL.get(code)
    if rows is None:
        ch = chr(code) if 32 <= code < 127 else None
        rows = GLYPHS.get(ch) if ch else None
        if rows is None: return px
    body = [[False] * 8 for _ in range(8)]
    for y, r in enumerate(rows):
        for x, c in enumerate(r):
            if c == '#': body[y][x] = True
    for y in range(8):
        for x in range(8):
            if body[y][x]: px[y][x] = 1 if y < 4 else 2
            elif x > 0 and y > 0 and body[y - 1][x - 1]: px[y][x] = 3
    return px

