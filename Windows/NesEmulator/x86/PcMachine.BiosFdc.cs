    /// <summary>On a board with the floppy controller: the V86 floppy code, and the IDE PIO code's mode dispatch (test al,al / jz) turned into a jump to it.</summary>
    private void InstallInt13Fdc()
    {
        if (Fdc == null) return;
        Array.Copy(Int13FdcCode, 0, Cpu.Mem, Rom + Int13Fdc, Int13FdcCode.Length);
        uint at = Int13Pio + 0x0b;                                  // 84 C0 74 4F -> E9 rel16 90
        int rel = (int)Int13Fdc - (int)(at + 3);
        Cpu.Mem[Rom + at] = 0xe9; Cpu.Mem[Rom + at + 1] = (byte)rel; Cpu.Mem[Rom + at + 2] = (byte)(rel >> 8); Cpu.Mem[Rom + at + 3] = 0x90;
    }

    /// <summary>True when the floppy read / write was handed to the controller code (V86 mode, a board with the controller, a disk in the drive,
    /// one track, no 64 KB DMA boundary crossed): the task is filled, nothing is moved here.</summary>
    private bool Int13FdcSetup(int dl, uint fn)
    {
        if (Fdc == null || (C.Flags & I386.VM) == 0 || dl is not (0 or 1) || fn is not (0x02 or 0x03) || _cdEmu != null) return false;
        if (Floppy[dl] is not { IsFloppy: true } d) return false;
        if (SegB(I386.SEG_CS) + C.Ip != Rom + Int13Pio) return false;
        if (Cpu.Mem[Rom + Int13Pio + 0x0b] != 0xe9) return false;   // (a ROM from a state saved before the controller code)
        int count = (int)AL;
        int cyl = (int)CH, sec = (int)(CL & 0x3f), head = (int)DH;
        if (count == 0 || sec == 0 || sec + count - 1 > d.Sectors || head >= d.Heads || cyl >= d.Cylinders) return false;
        uint lin = (C.SegSel[I386.SEG_ES] << 4) + BX;
        if ((lin & 0xffff) + count * 512 > 0x10000 || lin + count * 512 > 0x100000) return false;   // (a real BIOS: error 09h; ours keeps the C# path)
        var m = Cpu.Mem; uint t = Rom + Int13Task;
        bool write = fn == 0x03;
        int len = count * 512 - 1;
        m[t] = 4;
        m[t + 1] = (byte)dl; m[t + 2] = (byte)cyl; m[t + 3] = (byte)head; m[t + 4] = (byte)sec; m[t + 5] = (byte)d.Sectors;
        m[t + 6] = (byte)(write ? 0xc5 : 0xe6);
        m[t + 7] = (byte)(write ? 0x4a : 0x46);
        m[t + 8] = (byte)lin; m[t + 9] = (byte)(lin >> 8); m[t + 10] = (byte)(lin >> 16);
        m[t + 11] = (byte)len; m[t + 12] = (byte)(len >> 8);
        m[t + 13] = (byte)(d.Sectors switch { 9 => 2, 36 => 3, _ => 0 });
        m[t + 14] = (byte)(0x0c | dl | (0x10 << dl));
        AL = (uint)count;
        DiskStatus(dl, 0);
        return true;
    }
