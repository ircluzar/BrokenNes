def rgb(r, g, b): return (max(0, min(31, int(round(r))))) | (max(0, min(31, int(round(g)))) << 5) | (max(0, min(31, int(round(b)))) << 10)
def lerp(a, b, t): return a + (b - a) * t
def mix(c0, c1, t): return tuple(lerp(a, b, t) for a, b in zip(c0, c1))

# ------------------------------------------------------------------ the ROM's data banks

class Packer:
    """Blobs into 64 KB ROM banks $C1-$C7 (bank $C0 holds the code). A blob never crosses a bank; equal blobs are stored once."""
    FIRST = 1
    def __init__(self, banks):
        self.banks = [bytearray() for _ in range(banks)]
        self.where, self.labels, self.files = {}, [], []
    def put(self, blob, label=None):
        blob = bytes(blob)
        assert 0 < len(blob) <= 0x10000
        if blob in self.where:
            bank, off = self.where[blob]
        else:
            for b in range(self.FIRST, len(self.banks)):
                if len(self.banks[b]) + len(blob) <= 0x10000: break
            else: raise SystemExit('gen_testcart: the ROM is full')
            bank, off = b, len(self.banks[b])
            self.banks[b] += blob
            self.where[blob] = (bank, off)
        if label: self.labels.append((label, bank, off, len(blob)))
        return 0xC0 + bank, off
    def write(self, path):
        with open(path, 'w', newline='\n') as f:
            f.write('; generated by gen_testcart.py: do not edit. The data banks ($C1-$C7).\n.BASE $C0\n')
            for b in range(self.FIRST, len(self.banks)):
                data = self.banks[b]
                if not data: continue
                name = f'bank{b}.bin'
                with open(os.path.join(WORK, name), 'wb') as g: g.write(data)
                f.write(f'.BANK {b} SLOT 0\n.ORG $0000\n.SECTION "Data{b}" FORCE\nDataBank{b}:\n  .INCBIN "{name}"\n.ENDS\n')
            f.write('.BASE $00\n')
    def write_defs(self, path):
        with open(path, 'w', newline='\n') as f:
            f.write('; generated by gen_testcart.py: do not edit. Where each blob of the data banks is (24-bit addresses), and its length.\n')
            for label, bank, off, n in self.labels:
                f.write(f'.DEFINE {label} ${0xC0 + bank:02X}{off:04X}\n.DEFINE {label}_LEN {n}\n')

