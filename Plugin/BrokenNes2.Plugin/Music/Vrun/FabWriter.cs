using System.Collections.Generic;
using System.Linq;

namespace Vrun.Audio;

/// <summary>Emits converted songs as NESFab source - the format the VRUN
/// build bakes (music_data.fab): literal arrays, one `data` group per song.</summary>
public static class FabWriter
{
    /// <summary>The text a song adds to music_data.fab. The first song of a
    /// file (<paramref name="first"/>) also writes the header comment and the
    /// PERIOD_LO/PERIOD_HI tables.</summary>
    public static string SongText(SongResult song, bool first, string sourcePath)
    {
        var lines = new List<string>();
        if (first)
        {
            lines.Add($"// AUTO-GENERATED by engine/audio/converter (midi2nes) from {sourcePath}. Do not hand-edit.");
            var (lo, hi) = Midi2Nes.BuildPeriodTable();
            lines.Add(CtArray("PERIOD_LO", lo));
            lines.Add(CtArray("PERIOD_HI", hi));
        }
        // Each song gets its OWN data group, not one shared `/music` group.
        // NESFab places a function that reads a group into every bank that
        // group occupies - with one shared group, all 4 decoders of EVERY
        // song were copied into EVERY bank holding any song (480 copies in
        // a 12-song AudioPlayer; a 22-song roster didn't compile at all).
        lines.Add($"data /music_{song.Name}");
        for (int nes = 0; nes < 4; nes++)
        {
            byte[] data = song.Channels[nes];
            lines.Add($"    [] music_{song.Name}_{Midi2Nes.ChannelNames[nes]}");
            lines.Add($"        U[{data.Length}]({string.Join(", ", data.Select(b => b.ToString()))})");
        }
        return string.Join("\n", lines) + "\n";
    }

    // A compile-time constant array (not in a `data` group): directly
    // indexable with no `@`, like nes-mapbake.mjs's metatile tables.
    static string CtArray(string name, byte[] data) =>
        $"ct U[{data.Length}] {name} = U[{data.Length}]({string.Join(", ", data.Select(b => b.ToString()))})";
}
