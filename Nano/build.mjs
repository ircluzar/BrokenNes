// Builds Nano/dist from Nano/src: node Nano/build.mjs            (writes dist/)
//                                  node Nano/build.mjs --check    (rebuilds in memory and compares with dist/; exit 1 if they differ)
//
// No dependencies, no minifier: the shipped files are the sources, concatenated and wrapped, comments included.
//   dist/nano.js          the whole thing as a classic script (global BrokenNesNano, or CommonJS require)
//   dist/nano.mjs         the same as an ES module (default export + named exports)
//   dist/nano-worklet.js  only the audio worklet, for pages whose Content-Security-Policy forbids blob: scripts (create({workletUrl}))
//   dist/LICENSE.txt      the license text, which has to travel with the files
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.dirname(fileURLToPath(import.meta.url));
const read = (f) => fs.readFileSync(path.join(root, 'src', f), 'utf8').replace(/\r\n/g, '\n');

const chip = read('chip.js'), presets = read('presets.js'), engine = read('engine.js'), api = read('api.js');
const version = /const VERSION = '([^']+)'/.exec(api)[1];

const header = `/*! BrokenNes Nano ${version}: the BrokenNes NES sound chip as a web synth (AudioWorklet).
 *  Part of BrokenNes, Digital Lifeform License 1.1: the license text (LICENSE.txt) must accompany copies. Source: Nano/src in the BrokenNes repository;
 *  this file is generated by Nano/build.mjs and checked against Core's sound chip sample for sample (see Nano/README.md). */
`;

const kitFn = `function engineKit() {\n${chip}\n${presets}\n${engine}\nreturn { Chip, Engine, PRESETS, normalizePreset, roundEven, KIND_NAMES, KIND_CHANNELS, CPU_HZ, CHUNK };\n}\n`;

const b = api.indexOf('//#worklet-begin'), e = api.indexOf('//#worklet-end');
if (b < 0 || e < 0) throw new Error('worklet markers missing in src/api.js');
const workletFn = api.slice(b + '//#worklet-begin'.length, e).replace(/^\n/, '');
const nameMatch = /const PROCESSOR_NAME = '([^']+)'/.exec(api)[1];

const files = {};
files['nano.js'] = `${header}(function (root, factory) {
  if (typeof module === 'object' && module.exports) module.exports = factory();
  else root.BrokenNesNano = factory();
})(typeof self !== 'undefined' ? self : this, function () {
'use strict';
${kitFn}
${api}
return api;
});
`;
files['nano.mjs'] = `${header}const api = (function () {
'use strict';
${kitFn}
${api}
return api;
})();
export default api;
export const { version, create, support, noteNumber, renderOffline, toAudioBuffer, presets } = api;
`;
files['nano-worklet.js'] = `${header}'use strict';
${kitFn}
${workletFn}
workletMain(engineKit(), ${JSON.stringify(nameMatch)});
`;

const license = fs.readFileSync(path.join(root, '..', 'LICENSE.txt'), 'utf8').replace(/\r\n/g, '\n');
const dist = path.join(root, 'dist');
const check = process.argv.includes('--check');
let bad = 0;
function emit(name, data) {
  const target = path.join(dist, name);
  const buf = Buffer.isBuffer(data) ? data : Buffer.from(data, 'utf8');
  if (check) {
    const have = fs.existsSync(target) ? fs.readFileSync(target) : null;
    if (!have || !have.equals(buf)) { console.error(`DIFFERS: dist/${name}`); bad++; } else console.log(`same: dist/${name} (${buf.length} bytes)`);
  } else {
    fs.mkdirSync(dist, { recursive: true });
    fs.writeFileSync(target, buf);
    console.log(`wrote dist/${name} (${buf.length} bytes)`);
  }
}
for (const [n, d] of Object.entries(files)) emit(n, d);
emit('LICENSE.txt', license);
process.exit(bad ? 1 : 0);
