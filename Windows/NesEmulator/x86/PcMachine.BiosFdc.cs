// INT 13h floppy reads / writes from V86 mode through the 82077AA floppy controller (the PCI 430TX board only). Written for BrokenNes.
//
// Windows 98's IOS checks a V86 INT 13h per drive against the controller's ports, as it does for IDE (see Int13PioCode): a BIOS that reaches
// the floppy without them leaves drive A: in MS-DOS compatibility mode. So on a board with the controller, a floppy read / write from a V86
// VM is done the way a real BIOS does it: C# only fills the task at F000:DF00 (mode 4) and the code at F000:9800 (reached from the IDE PIO
// code's dispatch, patched to jump there) programs DMA channel 2, turns the motor on, seeks, issues READ / WRITE DATA and reads the result
// phase, polling the main status register. Everything else (and anything outside V86 mode) is still the C# service, so DOS sees no change.
// Source: PcMachine.BiosFdc.asm beside this file (NASM, -f bin, org F000:9800).

