    /// <summary>Index into <see cref="TripletIdsAndFlags"/> the boot ROM would use for this cartridge.</summary>
    public static int SelectEntry(byte[] rom)
    {
        bool nintendo = rom[0x14B] == 0x33 ? rom[0x144] == (byte)'0' && rom[0x145] == (byte)'1' : rom[0x14B] == 0x01;
        if (!nintendo) return 0;
        byte sum = 0;
        for (int i = 0x134; i < 0x144; i++) sum += rom[i];
        int c = Array.IndexOf(TitleChecksums, sum);
        if (c < 0) return 0;
        const int unambiguous = 65;
        if (c < unambiguous) return c;
        // Ambiguous checksum: try the 4th title letter in each row of the letter table.
        for (int k = c - unambiguous; k < FourthLetters.Length; k += 14, c += 14)
            if (FourthLetters[k] == rom[0x137]) return c;
        return 0;
    }

    public static (ushort[] bg, ushort[] obj0, ushort[] obj1) Pick(byte[] rom)
    {
        byte entry = TripletIdsAndFlags[SelectEntry(rom)];
        int row = entry & 0x1F, flags = entry >> 5;
        int o0 = PaletteOffsets[row * 3], o1 = PaletteOffsets[row * 3 + 1], o2 = PaletteOffsets[row * 3 + 2];
        // The boot ROM's "shuffle" flags decide which of the row's offsets each OBJ palette takes; BGP is always the third.
        int obp0 = (flags & 1) != 0 ? o0 : o2;
        int obp1 = (flags & 4) != 0 ? o1 : (flags & 2) != 0 ? o0 : o2;
        return (Read(o2), Read(obp0), Read(obp1));
    }

    /// <summary>Four colours starting at a byte offset into the palette table (some offsets straddle two palettes).</summary>
    private static ushort[] Read(int byteOffset)
    {
        var c = new ushort[4];
        for (int i = 0; i < 4; i++) c[i] = Colors[byteOffset / 2 + i];
        return c;
    }

    public static void Apply(PPU_GB ppu, GbCartridge cart)
    {
        var (bg, obj0, obj1) = Pick(cart.Rom);
        ppu.SetCompatPalettes(bg, obj0, obj1);
    }
}
