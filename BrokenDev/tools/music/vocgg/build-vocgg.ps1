<#
.SYNOPSIS
  Builds the Vaults GG .flp test ROM template the BrokenNes2 plugin carries (Plugin/BrokenNes2.Plugin/Resources/flpvocgg.gg + .txt).

.DESCRIPTION
  The game's OWN sound unit (VRUN_VOC_GG_dev src/voc_sound.c: the PSG music driver that plays the Game Boy version's song bytes, and
  src/sfx/voc_sfx_psg.c, compiled unchanged with the game's flags) + flp_gg_main.c (plays song 0 from power-on in the game's vblank
  order) + a song table written here (one song, its four streams reserved: 16,376 bytes each in slot-2 banks 58, 59, 61, 62; the
  pitch table mus_ptab exactly as the game's tools/psg/convert_music.py computes it; mus_nrate reserved, the plugin writes it from
  the song's noise table). SMSlib / crt0 are the ones the game's build.ps1 rebuilt (build\smslib-gg). Exit 0 when written.
#>
param([string]$Game = 'C:\Users\philt\OneDrive\Documents\PROJECTS\VRUN_VOC_GG_dev',
      [string]$Sdcc = 'T:\BrokenDev\env\toolchains\sdcc\4.6.0\sdcc', [string]$DevkitSms = 'T:\BrokenDev\env\toolchains\devkitsms\533ae57\devkitSMS',
      [Parameter(Mandatory)][string]$Out)
$ErrorActionPreference = 'Stop'
$here = Split-Path -Parent $MyInvocation.MyCommand.Path
$sdccExe = Join-Path $Sdcc 'bin\sdcc.exe'
$makesms = Join-Path $DevkitSms 'tools\makesms\Windows\makesms.exe'
$lib = Join-Path $Game 'build\smslib-gg\SMSlib_GG.lib'; $crt0 = Join-Path $Game 'build\smslib-gg\crt0_sms.rel'
foreach ($f in $sdccExe, $makesms, $lib, $crt0) { if (-not (Test-Path -LiteralPath $f)) { throw "not found: $f (build the game once: its build.ps1 rebuilds SMSlib)" } }
$env:PATH = (Join-Path $Sdcc 'bin') + ';' + $env:PATH
$obj = Join-Path $Out 'obj'
New-Item -ItemType Directory -Force -Path $obj | Out-Null
Get-ChildItem -LiteralPath $obj -File | Remove-Item -Force
$banks = 58, 59, 61, 62
# the song table (bank 0) and the four reserved streams
$ptab = 0..127 | ForEach-Object { $f = 440.0 * [Math]::Pow(2, ($_ - 69) / 12.0); [Math]::Min(65535, [int][Math]::Round(131072.0 / $f, [MidpointRounding]::ToEven)) }
$tab = @('/* GENERATED by build-vocgg.ps1: the .flp test ROM''s song table (one song, reserved streams). mus_ptab = tools/psg/convert_music.py''s. */',
    '#include <stdint.h>', '#include "music/gg/voc_music_gg.h"')
for ($i = 0; $i -lt 4; $i++) { $tab += "extern const uint8_t flp_s$i[];" }
$tab += 'const mus_song_t mus_songtab[1] = { { 0x0100, { ' + (($banks | ForEach-Object -Begin { $k = 0 } -Process { "{ flp_s$k, $_ }"; $k++ }) -join ', ') + ' } } };'
$tab += 'const uint8_t mus_track_song[22] = { 0 };'
$tab += 'const uint16_t mus_ptab[128] = { ' + ($ptab -join ', ') + ' };'
$tab += 'const uint8_t mus_nrate[128] = { 0 };'
Set-Content -LiteralPath (Join-Path $obj 'flp_tab.c') -Encoding ascii -Value $tab
for ($i = 0; $i -lt 4; $i++) { Set-Content -LiteralPath (Join-Path $obj "flp_s$i.c") -Encoding ascii -Value @('#include <stdint.h>', "const uint8_t flp_s$i[16376] = { 0xD0, 0xFF, 0xFF };") }
$inc = @('-I', (Join-Path $DevkitSms 'SMSlib\src'), '-I', (Join-Path $Game 'src'))
$common = @('-c', '-mz80', '--opt-code-speed') + $inc + @('-DTARGET_GG', '-DVOC_GG_GAME')
$fixed = @()
function Cc([string]$src, [string]$rel, [string[]]$extra = @()) {
    $a = $common + $extra + @('-o', $rel, $src)
    & $sdccExe @a
    if ($LASTEXITCODE -ne 0) { throw "sdcc $src" }
}
foreach ($s in @((Join-Path $Game 'src\voc_sound.c'), (Join-Path $here 'flp_gg_main.c'), (Join-Path $obj 'flp_tab.c'))) {
    $r = Join-Path $obj ([IO.Path]::GetFileNameWithoutExtension($s) + '.rel'); Cc $s $r; $fixed += $r
}
$bankRels = @{}
$r = Join-Path $obj 'voc_sfx_psg.rel'; Cc (Join-Path $Game 'src\sfx\voc_sfx_psg.c') $r @('--constseg', 'BANK60'); $bankRels[60] = $r
for ($i = 0; $i -lt 4; $i++) { $r = Join-Path $obj "flp_s$i.rel"; Cc (Join-Path $obj "flp_s$i.c") $r @('--constseg', "BANK$($banks[$i])"); $bankRels[$banks[$i]] = $r }
$place = @(); $ordered = @()
foreach ($b in ($bankRels.Keys | Sort-Object)) { $place += ('-Wl-b_BANK{0}=0x{1:X}' -f $b, ($b * 0x10000 + 0x8000)); $ordered += $bankRels[$b] }
$ihx = Join-Path $obj 'flpvocgg.ihx'
$a = @('-o', $ihx, '-mz80', '--no-std-crt0', '--data-loc', '0xC000', '-Wl-j', '-Wl-m', '-Wl-w') + $place + @($crt0) + $fixed + @($lib) + $ordered
& $sdccExe @a
if ($LASTEXITCODE -ne 0) { throw 'link' }
$rom = Join-Path $Out 'flpvocgg.gg'
& $makesms $ihx $rom
if ($LASTEXITCODE -ne 0) { throw 'makesms' }
$noi = @{}
foreach ($l in Get-Content ([IO.Path]::ChangeExtension($ihx, '.noi'))) { if ($l -match '^DEF (\S+) 0x([0-9A-Fa-f]+)') { $noi[$Matches[1]] = [Convert]::ToInt64($Matches[2], 16) } }
function Off([string]$sym) {
    if (-not $noi.ContainsKey($sym)) { throw "symbol $sym not in the .noi" }
    $v = $noi[$sym]; $bank = [int]($v -shr 16); $addr = [int]($v -band 0xFFFF)
    if ($bank -eq 0) { return $addr }
    return $bank * 0x4000 + ($addr -band 0x3FFF)
}
$bytes = [IO.File]::ReadAllBytes($rom)
$sha = { param($b) -join ([Security.Cryptography.SHA256]::HashData($b) | ForEach-Object { $_.ToString('x2') }) }
$commit = (& git -c safe.directory=* -C $Game rev-parse --short HEAD).Trim()
$drv = @((Join-Path $Game 'src\voc_sound.c'), (Join-Path $Game 'src\sfx\voc_sfx_psg.c'))
$drvSha = & $sha ([byte[]]($drv | ForEach-Object { [IO.File]::ReadAllBytes($_) } | ForEach-Object { $_ }))
$m = @('# BrokenNes2 .flp test ROM (Vaults GG): the game''s own sound unit + one reserved song. Made by BrokenDev/tools/music/vocgg/build-vocgg.ps1. Offsets are ROM file offsets.',
    'format = bn2-flp-vocgg', 'version = 1', "game = VRUN_VOC_GG_dev $commit", "driver-sha256 = $drvSha",
    ('nrate = 0x{0:X6} 128' -f (Off '_mus_nrate')))
for ($i = 0; $i -lt 4; $i++) { $m += ('stream{0} = 0x{1:X6} 16376' -f $i, (Off "_flp_s$i")) }
$m += ('frames = 0x{0:X4}' -f ($noi['_flp_frames'] -band 0xFFFF))
$m += "rom-bytes = $($bytes.Length)"
$m += "rom-sha256 = $(& $sha $bytes)"
Set-Content -LiteralPath (Join-Path $Out 'flpvocgg.txt') -Value $m -Encoding ascii
Write-Host "ok    $rom"
