// Builds Nano/dos/dist from Nano/dos/src:  node Nano/dos/build.mjs            (writes dist/ and the plugin's preset table)
//                                        node Nano/dos/build.mjs --check    (rebuilds in memory and compares; exit 1 if anything differs)
//
// No dependencies, no minifier.
//   dist/nano-dos.js         the whole library as a classic script (global BrokenNesNanoDOS, or CommonJS require), comments included
//   dist/nano-dos.mjs        the same as an ES module
//   dist/nano-dos-worklet.js  only the audio worklet, for pages whose Content-Security-Policy forbids blob: scripts
//   dist/nano-dos.lean.js    nano-dos.js without comments or indentation (the same code: test/engine.test.mjs renders both and compares)
//   dist/NOTICE.txt          the credits and licences that travel with the files
